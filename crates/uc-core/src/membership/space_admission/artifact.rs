use zeroize::Zeroizing;

macro_rules! define_redacted_artifact {
    ($(#[$metadata:meta])* $name:ident, $max_size:expr) => {
        $(#[$metadata])*
        #[derive(PartialEq, Eq)]
        pub struct $name(Vec<u8>);

        impl $name {
            pub fn from_bytes(bytes: Vec<u8>) -> Result<Self, AdmissionArtifactError> {
                if bytes.is_empty() {
                    return Err(AdmissionArtifactError::Empty);
                }
                if bytes.len() > $max_size {
                    return Err(AdmissionArtifactError::Oversized);
                }
                Ok(Self(bytes))
            }

            pub fn as_bytes(&self) -> &[u8] {
                &self.0
            }
        }

        impl std::fmt::Debug for $name {
            fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                formatter
                    .debug_struct(stringify!($name))
                    .field("byte_len", &self.0.len())
                    .finish_non_exhaustive()
            }
        }
    };
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
/// 构造不透明准入材料时的错误。
///
/// 准入规则只确认材料存在且处于允许范围，不解释材料内部内容。
pub enum AdmissionArtifactError {
    #[error("the admission artifact is empty")]
    Empty,
    #[error("the admission artifact exceeds its protocol limit")]
    Oversized,
}

/// Opaque local private state generated by the Joiner for one admission.
#[derive(PartialEq, Eq)]
pub struct AdmissionJoinerPrivateState(Zeroizing<Vec<u8>>);

impl AdmissionJoinerPrivateState {
    pub fn from_bytes(bytes: Vec<u8>) -> Result<Self, AdmissionArtifactError> {
        if bytes.is_empty() {
            return Err(AdmissionArtifactError::Empty);
        }
        if bytes.len() > 4 * 1024 * 1024 {
            return Err(AdmissionArtifactError::Oversized);
        }
        Ok(Self(Zeroizing::new(bytes)))
    }

    pub fn as_bytes(&self) -> &[u8] {
        &self.0
    }
}

impl std::fmt::Debug for AdmissionJoinerPrivateState {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("AdmissionJoinerPrivateState")
            .field("byte_len", &self.0.len())
            .finish_non_exhaustive()
    }
}

